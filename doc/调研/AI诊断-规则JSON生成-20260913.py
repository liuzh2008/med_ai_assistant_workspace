def build(entry, category, priority=10):
    return {
        'keywordMatch': entry['keyword'],
        'ruleName': entry['name'],
        'clinicalExperience': entry['text'],
        'diagnosisCategory': category,
        'priority': priority,
        'isActive': True,
    }


def main():
    plan = []
    for e in RULES_NON_DIAG:
        plan.append((e, build(e, NON_DIAG)))
    for e in RULES_OP:
        plan.append((e, build(e, FORBIDDEN)))

    print('待生成规则文件 %d 个：' % len(plan))
    for e, obj in plan:
        print('  - [%s] %s | keyword=%s | 文本 %d 字符'
              % (obj['diagnosisCategory'], e['file'], obj['keywordMatch'], len(obj['clinicalExperience'])))

    with open(MANIFEST, encoding='utf-8') as f:
        manifest = json.load(f)
    have = {r['ruleName'] for r in manifest.get('rules', [])}
    new_entries = [e for e, _ in plan if e['name'] not in have]
    print('\nmanifest 现有 %d 条，待新增 %d 条（version=%s，下发时由 /submit-clinical-rules 递增）'
          % (len(manifest.get('rules', [])), len(new_entries), manifest.get('version')))

    if not APPLY:
        print('\n[dry-run] 未写入。加 --apply 执行。')
        return

    for e, obj in plan:
        path = os.path.join(RULES_DIR, e['file'])
        _safe_write(path, obj)
    print('\n[OK] 规则文件已写入 %s' % RULES_DIR)

    for e, _ in plan:
        if e['name'] not in have:
            manifest['rules'].append({
                'keywordMatch': e['keyword'],
                'ruleName': e['name'],
                'file': 'rules/' + e['file'],
            })
    _safe_write(MANIFEST, manifest)
    print('[OK] manifest 已更新：%d 条规则' % len(manifest['rules']))


if __name__ == '__main__':
    main()
