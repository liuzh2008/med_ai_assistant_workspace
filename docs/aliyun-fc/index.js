// ==================== 构建知识库上下文 ====================
function getKnowledgeContext() {
  if (!Array.isArray(KNOWLEDGE_DATA) || KNOWLEDGE_DATA.length === 0) {
    return '';
  }

  return KNOWLEDGE_DATA
    .filter(item => item && typeof item.content === 'string')
    .map(item => item.content)
    .join('\n\n');
}

// ==================== 限流器（内存） ====================
const rateLimitMap = new Map();
const RATE_LIMIT_PER_HOUR = 20;
const CLEANUP_INTERVAL = 60 * 60 * 1000; // 1小时清理一次过期记录

// 定期清理
if (typeof setInterval !== 'undefined') {
  setInterval(() => {
    const now = new Date();
    const currentHourKey = `${now.getUTCFullYear()}-${now.getUTCMonth() + 1}-${now.getUTCDate()}-${now.getUTCHours()}`;
    for (const key of rateLimitMap.keys()) {
      if (!key.endsWith(`:${currentHourKey}`)) {
        rateLimitMap.delete(key);
      }
    }
  }, CLEANUP_INTERVAL);
}

function checkRateLimit(ip) {
  const now = new Date();
  const hourKey = `${now.getUTCFullYear()}-${now.getUTCMonth() + 1}-${now.getUTCDate()}-${now.getUTCHours()}`;
  const key = `${ip}:${hourKey}`;
  const count = rateLimitMap.get(key) || 0;

  if (count >= RATE_LIMIT_PER_HOUR) {
    return { allowed: false, remaining: 0 };
  }

  rateLimitMap.set(key, count + 1);
  return { allowed: true, remaining: RATE_LIMIT_PER_HOUR - count - 1 };
}

// ==================== CORS ====================
function getCorsHeaders(origin) {
  return {
    'Access-Control-Allow-Origin': origin || '*',
    'Access-Control-Allow-Methods': 'POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type',
    'Access-Control-Max-Age': '86400',
  };
}

// ==================== 辅助函数 ====================
function jsonResponse(statusCode, data, corsOrigin) {
  return {
    statusCode,
    headers: {
      ...getCorsHeaders(corsOrigin),
      'Content-Type': 'application/json; charset=utf-8',
    },
    body: JSON.stringify(data),
  };
}

// ==================== 主处理逻辑 ====================
async function handleRequest(request, env) {
  const corsOrigin = request.headers?.origin || '*';

  // --- 路由 ---
  const url = request.path || '/';
  const method = request.method || 'GET';

  // OPTIONS 预检
  if (method === 'OPTIONS') {
    return {
      statusCode: 204,
      headers: getCorsHeaders(corsOrigin),
    };
  }

  // 只接受 POST /api/chat
  if (method !== 'POST' || !url.endsWith('/api/chat')) {
    return jsonResponse(404, { error: 'Not Found' }, corsOrigin);
  }

  // --- 限流 ---
  const clientIp = (request.headers?.['x-forwarded-for'] || '').split(',')[0].trim() || 'unknown';
  const rateLimit = checkRateLimit(clientIp);
  if (!rateLimit.allowed) {
    return jsonResponse(429, { error: '请求过于频繁，请稍后再试' }, corsOrigin);
  }

  // --- 解析请求体 ---
  let body;
  try {
    body = typeof request.body === 'string' ? JSON.parse(request.body) : (request.body || {});
  } catch (e) {
    return jsonResponse(400, { error: '请求体格式错误' }, corsOrigin);
  }

  const message = body.message;
  if (!message || typeof message !== 'string') {
    return jsonResponse(400, { error: 'message 字段必填且必须为字符串' }, corsOrigin);
  }

  // --- 构建消息 ---
  const knowledgeContext = getKnowledgeContext();
  const messages = [
    {
      role: 'system',
      content: SYSTEM_PROMPT + (knowledgeContext
        ? '\n\n以下是系统知识库内容，请基于这些内容回答用户问题：\n' + knowledgeContext
        : ''),
    },
  ];

  if (Array.isArray(body.history)) {
    for (const h of body.history) {
      if (h && typeof h.role === 'string' && typeof h.content === 'string') {
        messages.push({ role: h.role, content: h.content });
      }
    }
  }
  messages.push({ role: 'user', content: message });

  // --- 读取 API Key ---
  const apiKey = process.env.DEEPSEEK_API_KEY || env?.DEEPSEEK_API_KEY;
  if (!apiKey) {
    return jsonResponse(500, { error: '服务配置错误：未设置 DEEPSEEK_API_KEY' }, corsOrigin);
  }

  // --- 调用 DeepSeek API（非流式） ---
  let apiResponse;
  try {
    apiResponse = await fetch('https://api.deepseek.com/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${apiKey}`,
      },
      body: JSON.stringify({
        model: 'deepseek-v4-flash',
        messages,
        stream: false,
        temperature: 0.7,
        max_tokens: 4096,
      }),
    });
  } catch (e) {
    return jsonResponse(502, { error: 'AI 服务调用失败', detail: String(e) }, corsOrigin);
  }

  if (!apiResponse.ok) {
    let errorText;
    try {
      errorText = await apiResponse.text();
    } catch (e) {
      errorText = String(e);
    }
    return jsonResponse(502, {
      error: 'AI 服务调用失败',
      status: apiResponse.status,
      detail: errorText,
    }, corsOrigin);
  }

  // --- 解析响应 ---
  let result;
  try {
    result = await apiResponse.json();
  } catch (e) {
    return jsonResponse(502, { error: 'AI 服务响应解析失败' }, corsOrigin);
  }

  const content = result.choices?.[0]?.message?.content || '';
  return jsonResponse(200, { content }, corsOrigin);
}

// ==================== 入口 ====================
exports.handler = async (event, context) => {
  try {
    const request = JSON.parse(event.toString());
    return await handleRequest(request, context);
  } catch (error) {
    return jsonResponse(500, { error: '服务器内部错误', detail: String(error) }, '*');
  }
};
